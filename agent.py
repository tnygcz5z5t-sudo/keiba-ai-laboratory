
import os
import time
from datetime import datetime
from pathlib import Path
from google import genai

MODELS = [
    "gemini-3.8-flash",
    "gemini-3.5-flash-lite",
]

client = genai.Client(
    api_key=os.environ["GEMINI_API_KEY"]
)

theme = os.getenv(
    "RESEARCH_THEME",
    "基礎スピードと減速耐性の識別可能性および数学的欠陥の修正"
)

prompt = """
あなたは競走馬の能力評価モデルを研究する専門AIです。
今回は第4次研究です。

第3次研究の成果と問題点を引き継ぎ、モデルの数学的妥当性を再検討してください。

【研究の基本方針】

■ 基礎スピード
基礎スピードとは、追走したときに脚を溜められる速度水準である。
単純な最高速度や前半の速さではない。
後半の減速結果を定義に混ぜてはいけない。

■ 減速耐性
高い負荷を受けた後でも速度を維持する能力に関係する概念。
ただし公開競走データから直接測定できるのは減速の程度であり、
生理学的な乳酸処理能力そのものではない。

■ レースラップ
レース全体のラップは基本的に先頭馬のラップである。
各馬の個別ラップとして扱ってはいけない。

■ データの制約
個別馬の区間速度や生理的余力は、一般的な公開データだけでは
直接観測できない場合がある。
観測値・計算値・推定値・取得困難な値を区別すること。

【第3次研究で提案されたモデル】

前・中盤速度：
v_pre = (D - 600) / (T - t_last3F)

終盤速度：
v_end = 600 / t_last3F

速度差：
Δv = v_end - v_pre

基礎スピードモデル：
v_pre = μ_pre + Race_j + θ_base_i + error

減速耐性モデル：
Δv = μ_delta + Race'_j - γ * v_pre
      + θ_resist_i + error

【第3次研究で発見された問題】

1. v_preは前・中盤の平均速度であり、
   中盤の巡航速度そのものではない。

2. Δvの中に-v_preが含まれているため、
   Δvを目的変数としてv_preを説明変数に使うと、
   数学的な結合による見せかけの相関が発生する。

3. 基礎スピードと減速耐性が別能力であることは、
   両者が統計的に無相関であることを意味しない。

4. 同じ速度でも、馬が余裕を持って追走しているか、
   限界に近い負荷で走っているかは公開データだけでは
   直接判定できない。

【今回の研究課題】

第1課題：
前・中盤平均速度 v_pre が基礎スピードの代理指標として
どの程度有効か検討すること。

以下を区別すること。
・前半の加速
・中盤の巡航
・終盤の加速または減速

公開データで区別できるものとできないものを明確にすること。

第2課題：
数学的結合による見せかけの相関を回避する方法を提案すること。

Δv = v_end - v_pre を目的変数にする方法の問題を説明し、
代替となる目的変数・統計モデルを複数提案すること。

単にv_preを説明変数から外すだけでなく、
負荷の影響をどのように扱うべきか検討すること。

第3課題：
基礎スピードと減速耐性を別々に推定するモデルを設計すること。

ただし、両者の相関を強制的にゼロにしてはいけない。
能力の概念的な区別と統計的な独立性を混同しないこと。

馬ごとの潜在能力を推定する場合、
同一馬の複数レースを使う階層モデルや混合効果モデルも検討すること。

第4課題：
基礎スピードを識別するために必要なデータを整理すること。

以下のデータを検討する。
・個別馬の区間タイム
・個別馬の位置情報
・レース全体のラップ
・通過順位
・コーナー順位
・着差
・走破タイム
・上がり3ハロン
・斤量
・競馬場
・距離
・馬場状態
・騎手
・頭数

データがない場合に、どの能力が識別不能になるかも示すこと。

第5課題：
公開競走データのみを使う場合の、
現実的な最小モデルを再設計すること。

複雑さよりも、
・計算可能であること
・再現可能であること
・誤差を把握できること
・仮説を反証できること
を優先すること。

第6課題：
モデルの検証方法を設計すること。

以下を含めること。
・単純な基準モデルとの比較
・時系列での訓練・検証分割
・馬単位のデータ漏洩対策
・MAE、RMSEなどの評価指標
・予測精度が改善しない場合の判断
・能力スコアの再現性の検証

第7課題：
最終的な能力スコアの設計方針を提案すること。

基礎スピードと減速耐性を別々のスコアにする。
ただし、両者の相関を無理にゼロにしない。
推定の不確実性も可能なら表示する。

【厳守事項】

・実際にデータ検証していないことを検証済みと書かない。
・根拠のない精度や誤差の数値を作らない。
・相関と因果関係を区別する。
・数学的結合による相関を能力の証拠にしない。
・数式の変数、単位、次元を明記する。
・識別できない能力は識別できないと報告する。
・都合のよい結論に誘導しない。
・既存の競馬理論を無条件に正解としない。

最後に以下を分けて報告すること。

1. 今回確定できたこと
2. 仮説として残ること
3. 現在のデータでは識別できないこと
4. 次に実データで検証すべきこと

研究テーマ：
""" + theme


def run_research():
    last_error = None

    for model in MODELS:
        for attempt in range(3):
            try:
                print(f"使用モデル: {model}")
                print(f"試行回数: {attempt + 1}")

                response = client.models.generate_content(
                    model=model,
                    contents=prompt
                )

                report = response.text

                if not report:
                    raise RuntimeError("AIから空の回答が返されました")

                output_dir = Path("reports")
                output_dir.mkdir(exist_ok=True)

                timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
                output_file = output_dir / f"AI01_Research04_{timestamp}.md"

                output_file.write_text(
                    f"# AI-01 第4次研究レポート\n\n"
                    f"使用モデル：{model}\n\n"
                    f"{report}",
                    encoding="utf-8"
                )

                print(f"研究レポート保存完了: {output_file}")
                return

            except Exception as error:
                last_error = error
                print(f"エラー: {error}")
                time.sleep(5)

    raise RuntimeError(
        f"すべてのモデルで研究に失敗しました: {last_error}"
    )


if __name__ == "__main__":
    run_research()
